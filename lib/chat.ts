export interface ChatResult {
  status: number;
  body: { reply?: string; error?: string };
}

export async function handleChat(payload: any): Promise<ChatResult> {
  try {
    const { message, history } = payload ?? {};

    if (!message || typeof message !== 'string') {
      return { status: 400, body: { error: 'Сообщение обязательно' } };
    }

    // Try Gemini API with a 5-second timeout
    const client = getAiClient();
    if (client) {
      try {
        const contents: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = [];

        if (Array.isArray(history)) {
          for (const item of history.slice(-6)) {
            if (item.role === 'user' || item.role === 'model') {
              contents.push({
                role: item.role,
                parts: [{ text: item.text }],
              });
            }
          }
        }

        contents.push({
          role: 'user',
          parts: [{ text: message }],
        });

        const geminiPromise = client.models.generateContent({
          model: 'gemini-3.8-flash',
          contents,
          config: {
            systemInstruction: SYSTEM_INSTRUCTION,
            temperature: 0.7,
            topP: 0.95,
          },
        });

        const timeoutPromise = new Promise<never>((_, reject) =>
          setTimeout(() => reject(new Error('Gemini API timeout')), 5000)
        );

        const response = (await Promise.race([geminiPromise, timeoutPromise])) as any;

        const replyText = response?.text;
        if (replyText) {
          return { status: 200, body: { reply: replyText } };
        }
      } catch (geminiError: any) {
        console.warn('Gemini API call skipped or timed out, using intelligent travel knowledge base:', geminiError?.message || geminiError);
      }
    }

    // Intelligent fallback responder
    return { status: 200, body: { reply: getIntelligentFallbackResponse(message) } };
  } catch (err: any) {
    console.error('Error handling /api/chat:', err);
    return {
      status: 500,
      body: {
        error: 'Ошибка при обработке сообщения',
        reply: 'Извините, произошла небольшая заминка. Пожалуйста, напишите нам в WhatsApp по номеру +996 (555) 12-34-56 или повторите вопрос!',
      },
    };
  }
}
